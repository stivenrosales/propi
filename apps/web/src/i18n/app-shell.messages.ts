export type ShellT = ReturnType<typeof shell.t>;

const STATES = new Set(["pending", "approved", "fulfilled", "rejected", "cancelled", "open", "draft", "closed", "active", "archived", "completed", "delivered", "refunded", "funding", "funded"]);

/** A lifecycle state's name; an unknown state reads as itself, capitalized. */
export function stateName(t: ShellT, state: string): string {
  return STATES.has(state) ? t(`state.${state}` as "state.open") : state.charAt(0).toUpperCase() + state.slice(1);
}
